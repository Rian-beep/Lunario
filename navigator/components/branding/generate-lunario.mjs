import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const vendor = new URL("../../public/branding/lunario/", import.meta.url);
const manifest = JSON.parse(readFileSync(new URL("provenance.json", vendor), "utf8"));
for (const [path, expected] of Object.entries(manifest.files)) {
  const bytes = readFileSync(new URL(path, vendor));
  if (bytes.length !== expected.bytes || createHash("sha256").update(bytes).digest("hex") !== expected.sha256) {
    throw new Error(`Pinned Lunario source changed: ${path}`);
  }
}
const read = path => readFileSync(new URL(path, vendor), "utf8");
const data = (path, mime) => `data:${mime};base64,${readFileSync(new URL(path, vendor)).toString("base64")}`;
const font = data("loader/fonts/geist-mono-regular.woff2", "font/woff2");
const css = read("loader/loader.css").replace('url("fonts/geist-mono-regular.woff2")', `url("${font}")`);
const content = `// Generated by components/branding/generate-lunario.mjs; do not hand-edit.\n` +
  `// Exact vendor sources: public/branding/lunario/provenance.json. Only the runtime CSS font URL is inlined.\n` +
  Object.entries({
    LUNARIO_WORDMARK: data("assets/logo-dark.svg", "image/svg+xml"),
    LUNARIO_WORDMARK_ON_DARK: data("assets/logo-white.svg", "image/svg+xml"),
    LUNARIO_MARK: data("assets/logo-mark-dark.svg", "image/svg+xml"),
    LUNARIO_LOADER_CSS: css,
    LUNARIO_LOADER_JS: read("loader/loader.js"),
  }).map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`).join("");
const output = new URL("lunario-vendor.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== content) throw new Error("Lunario runtime is stale; run node components/branding/generate-lunario.mjs");
} else writeFileSync(fileURLToPath(output), content);
