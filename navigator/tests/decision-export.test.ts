import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { decodeCatalog } from "../lib/catalog";
import { DEFAULT_FLIGHT } from "../lib/flight";
import { DEFAULT_MISSION } from "../lib/mission";
import { DEFAULT_OPERATIONS, DEFAULT_REQUIREMENTS } from "../lib/planning-types";
import { parseEvidenceManifest } from "../lib/provenance";
import { evidenceScopeKey } from "../lib/assessment";
import { createDecisionPackage, decisionPackageCsv, importDecisionPackage, MAX_DECISION_PACKAGE_BYTES, printableDecisionHtml, stringifyDecisionPackage } from "../lib/decision-export";
import type { ScenarioState } from "../lib/scenario";
const catalog = decodeCatalog(JSON.parse(readFileSync("public/data/catalog.json", "utf8")));
const manifest = parseEvidenceManifest(JSON.parse(readFileSync("public/data/evidence-manifest.json", "utf8")));
const base = (): ScenarioState => structuredClone({ schemaVersion: 2, siteId: catalog.sites[0].id, custom: null, startIndex: 100, endIndex: 102, heightM: 2, arrayHeightM: 2, antennaHeightM: 10, mission: DEFAULT_MISSION, flight: DEFAULT_FLIGHT, radio: { lossDb: 0 }, operations: { ...DEFAULT_OPERATIONS, loadSegments: [{ id: "鑽孔–é", startOffsetHours: 0, endOffsetHours: 1, additionalW: 3 }] }, requirements: DEFAULT_REQUIREMENTS });
test("Unicode scenario roundtrip recomputes and keeps complete forcing, units, provenance and exclusive UTC end", () => {
  const state = base();
  const pkg = createDecisionPackage(catalog, state, manifest, { ...state, antennaHeightM: 2 });
  const decoded = importDecisionPackage(stringifyDecisionPackage(pkg), catalog, manifest);
  assert.deepEqual(decoded.state, state);
  assert.equal(decoded.historicalTrusted, false);
  assert.equal(decoded.assessment.scenarioKey, pkg.assessment.scenarioKey);
  assert.equal(decoded.changes.length, 0);
  assert.ok(pkg.differences?.some((diff) => diff.path === "antennaHeightM"));
  assert.equal(Date.parse(pkg.interval.endUtcExclusive) - Date.parse(pkg.interval.startUtc), 3 * catalog.meta.stepHours * 3600000);
  assert.match(pkg.interval.startUtc, /Z$/);
  assert.equal(pkg.frame, catalog.meta.frame);
  assert.equal(pkg.sources.length, manifest.entries.length);
  const raw = pkg.rawTimeSeries as { array: { sunEl: unknown[] }; antenna: { earthEl: unknown[] } };
  assert.ok(Array.isArray(raw.array.sunEl));
  assert.equal(raw.array.sunEl.length, 3);
  assert.equal(raw.antenna.earthEl.length, 3);
  assert.deepEqual(state, base(), "export did not mutate scenario");
});
test("manual pass cannot certify external evidence or overwrite a current recomputation", () => {
  const state = base();
  state.requirements.requiredExternal = ["thermal-survival"];
  state.externalAssessments = [{ id: "thermal-survival", status: "reported-pass", source: "評估 report", author: "é", notes: "external", scenarioKey: evidenceScopeKey(state, manifest.datasetId) }];
  const pkg = createDecisionPackage(catalog, state, manifest);
  const current = pkg.assessment.outcome;
  pkg.assessment.outcome = "passes-assessed";
  pkg.assessment.constraints.forEach((constraint) => { constraint.state = "pass"; });
  const result = importDecisionPackage(pkg, catalog, manifest);
  assert.equal(result.historicalAssessment.outcome, "passes-assessed");
  assert.equal(result.assessment.outcome, current);
  assert.notEqual(result.assessment.outcome, "passes-assessed");
  assert.equal(result.assessment.constraints.find((row) => row.id === "thermal-survival")?.state, "conditional");
});
test("changed dataset, model and source hash versions are explicit and current evidence wins", () => {
  const pkg = createDecisionPackage(catalog, base(), manifest);
  pkg.modelVersion = "historical-model";
  pkg.assessment.modelVersion = "historical-model";
  const next = structuredClone(manifest);
  next.datasetId += "-new";
  next.entries[0].sha256 = "a".repeat(64);
  next.entries[0].version = "new-version";
  const result = importDecisionPackage(pkg, catalog, next);
  assert.equal(result.message, "Recomputed using different evidence/model");
  assert.equal(result.assessment.datasetId, next.datasetId);
  for (const field of ["datasetId", "modelVersion", `sources[${encodeURIComponent(next.entries[0].id)}].sha256`, `sources[${encodeURIComponent(next.entries[0].id)}].version`]) assert.ok(result.changes.some((change) => change.path === field));
});
test("unknown horizon samples are portable nulls and remain unknown after recomputation", () => {
  const state = { ...base(), custom: { lat: -85, lon: 20 }, arrayHeightM: 10 };
  const pkg = createDecisionPackage(catalog, state, manifest);
  const raw = pkg.rawTimeSeries as { array: { sunHorizon: unknown[] } };
  assert.ok(raw.array.sunHorizon.every((sample) => sample === null));
  assert.match(stringifyDecisionPackage({ data: new Float64Array([NaN, Infinity, -Infinity, 0]) }), /null/);
  assert.deepEqual(JSON.parse(stringifyDecisionPackage({ data: new Float64Array([NaN, Infinity, -Infinity, 0]) })), { data: [null, null, null, 0] });
  const imported = importDecisionPackage(pkg, catalog, manifest);
  assert.notEqual(imported.assessment.outcome, "passes-assessed");
});
test("legacy state migrates with catalog step and bounds; unsupported coverage is rejected", () => {
  const pkg = createDecisionPackage(catalog, base(), manifest);
  const legacy = pkg.scenario as unknown as Record<string, unknown>;
  delete legacy.schemaVersion; delete legacy.arrayHeightM; delete legacy.antennaHeightM; delete legacy.requirements; delete legacy.operations;
  const result = importDecisionPackage(pkg, catalog, manifest);
  assert.equal(result.state.schemaVersion, 2);
  assert.equal(result.state.antennaHeightM, result.state.heightM);
  const outside = { ...manifest, validUntilUtcExclusive: new Date(catalog.t0ms + 10 * 3600000).toISOString() };
  assert.throws(() => importDecisionPackage(pkg, catalog, outside), /outside prepared evidence coverage/);
  pkg.scenario.endIndex = catalog.meta.n - 1;
  assert.throws(() => importDecisionPackage(pkg, catalog, manifest), /invalid scenario/);
});
test("malformed, unsupported, oversized UTF-8 and incomplete packages fail without mutating caller", () => {
  const pkg = createDecisionPackage(catalog, base(), manifest), snapshot = structuredClone(pkg);
  assert.throws(() => importDecisionPackage("{bad", catalog, manifest));
  assert.throws(() => importDecisionPackage({ ...pkg, packageVersion: 2 }, catalog, manifest), /Unsupported/);
  assert.throws(() => importDecisionPackage({ ...pkg, cancelled: true }, catalog, manifest), /Unsupported/);
  assert.throws(() => importDecisionPackage({ ...pkg, rawTimeSeries: {} }, catalog, manifest), /Malformed raw/);
  assert.throws(() => importDecisionPackage({ ...pkg, sources: [{ id: "bad" }] }, catalog, manifest), /Malformed or duplicate source/);
  assert.throws(() => importDecisionPackage({ ...pkg, events: "not-events" }, catalog, manifest), /Malformed decision package/);
  assert.throws(() => importDecisionPackage({ ...pkg, assessment: { outcome: "passes-assessed" } }, catalog, manifest), /Malformed historical/);
  assert.throws(() => importDecisionPackage('"' + "é".repeat(MAX_DECISION_PACKAGE_BYTES / 2) + '"', catalog, manifest), /1 MB UTF-8/);
  assert.deepEqual(pkg, snapshot);
});
test("CSV guards formula text, tabs and carriage returns while retaining true numeric negatives and blank unknowns", () => {
  const pkg = createDecisionPackage(catalog, base(), manifest);
  pkg.datasetId = "=HYPERLINK(\"bad\")";
  pkg.assessment.constraints = ["+cmd", "-cmd", "@cmd", "\tplain", "\rplain"].map((text) => ({ ...pkg.assessment.constraints[0], id: text, actual: -5, limit: null, margin: null, reasonCode: text }));
  const csv = decisionPackageCsv(pkg);
  assert.ok(csv.includes('"\'=HYPERLINK(""bad"")"'));
  for (const text of ["+cmd", "-cmd", "@cmd", "\tplain", "\rplain"]) assert.ok(csv.includes('"\'' + text + '"'));
  assert.ok(csv.includes(',"-5","","",'));
  assert.ok(!csv.includes('"\'-5"'));
});
test("printable report puts escaped provenance and assumptions before result and has accessible requirement table", () => {
  const pkg = createDecisionPackage(catalog, base(), manifest);
  pkg.datasetId = "<script>alert('x')</script>";
  pkg.assessment.constraints[0].explanation = "<img src=x onerror=bad>";
  const html = printableDecisionHtml(pkg);
  assert.ok(html.indexOf("Provenance and assumptions") < html.indexOf("Assessed result"));
  assert.ok(!html.includes("<script>")); assert.ok(!html.includes("<img"));
  assert.ok(html.includes("&lt;script&gt;")); assert.ok(html.includes('<th scope="col">')); assert.ok(html.includes("exclusive end"));
});
