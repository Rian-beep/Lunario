export function glossaryFor(label: string): Entry | undefined {
  if (label.startsWith("Critical Earth visibility: ") && label.length > "Critical Earth visibility: ".length) return GLOSSARY["Critical contact requirement"];
  const key = Object.hasOwn(GLOSSARY, label)
    ? label
    : Object.hasOwn(ALIASES, label)
      ? ALIASES[label]
      : undefined;
  return key ? GLOSSARY[key] : undefined;
}
